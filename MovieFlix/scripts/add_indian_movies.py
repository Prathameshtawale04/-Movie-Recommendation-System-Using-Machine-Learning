def expand_dataset():
    """Merges the 100 Indian movies into tmdb_movies.json."""
    RAW_MOVIES_JSON.parent.mkdir(parents=True, exist_ok=True)

    existing_movies = []
    if RAW_MOVIES_JSON.exists():
        try:
            with open(RAW_MOVIES_JSON, "r", encoding="utf-8") as f:
                existing_movies = json.load(f)
        except Exception:
            existing_movies = []

    existing_ids = {m["id"] for m in existing_movies}
    added_count = 0

    for m in INDIAN_MOVIES_100:
        if m["id"] not in existing_ids:
            existing_movies.append(m)
            existing_ids.add(m["id"])
            added_count += 1

    with open(RAW_MOVIES_JSON, "w", encoding="utf-8") as f:
        json.dump(existing_movies, f, indent=2, ensure_ascii=False)

    print(f"Successfully added {added_count} Indian movies to {RAW_MOVIES_JSON}!")
    print(f"Total movies now in raw dataset: {len(existing_movies)}")


if __name__ == "__main__":
    expand_dataset()
